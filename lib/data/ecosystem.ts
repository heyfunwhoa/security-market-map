function category(input: {
  id: string;
  name: string;
  group: Category["group"];
  domainIds: string[];
  definition: string;
  buyerQuestion: string;
  buyerOwner: string;
  triggers: string[];
  budgetSource: string;
  outcomes: string[];
  adjacentCategoryIds: string[];
  exampleWorkflow: string;
  flow: Category["flow"];
  layer?: Category["layer"];
}): Category {
  return { slug: input.id, layer: input.layer ?? "core", ...input };
}

